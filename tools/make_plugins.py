"""Writes every SynTHBloK plugin from tools/lineup.json (which module goes where) and tools/modules.json (each
module's name, description and tags):
  - the MTX pack at the repo root: plugin.json (modules), src/plugin.cpp, the SOURCES block in the Makefile;
  - each single in singles/<slug>/: plugin.json, Makefile, single.cpp (the module registration).
Versions already in a plugin.json are kept (tools/release.ps1 bumps them). Each single's Makefile lists the res/ files
its modules load, found by scanning their sources, and copies them (and the licence) in from the repo root at build.
    python3 tools/make_plugins.py          (run from anywhere; checks the lineup and stops on a problem)"""
import glob, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')
HEAD = ['slug', 'name', 'version', 'license', 'brand', 'author', 'authorEmail', 'authorUrl', 'pluginUrl',
        'manualUrl', 'sourceUrl', 'changelogUrl', 'donateUrl']
GEN = 'Generated by tools/make_plugins.py from tools/lineup.json: edit those, then run it again.'


def load(path):
    with open(os.path.join(ROOT, path), encoding='utf-8') as f:
        return json.load(f)


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    old = open(full, encoding='utf-8').read() if os.path.exists(full) else None
    if old != text:
        with open(full, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print('wrote', path)


def model_vars():
    """module slug -> the C++ Model* variable that createModel makes"""
    out = {}
    for f in glob.glob(os.path.join(SRC, '*.cpp')):
        for var, slug in re.findall(r'Model\*\s*(\w+)\s*=\s*createModel<[^>]*>\(\s*"([^"]+)"', open(f, encoding='utf-8', errors='replace').read()):
            out[slug] = var
    return out


def res_files(sources):
    """res/ paths the sources (and the headers they include) load"""
    seen, found = set(), set()
    def walk(name):
        path = os.path.join(SRC, name)
        if name in seen or not os.path.exists(path):
            return
        seen.add(name)
        text = open(path, encoding='utf-8', errors='replace').read()
        found.update(r for r in re.findall(r'"(res/[^"%]+)"', text) if os.path.exists(os.path.join(ROOT, r)))
        for inc in re.findall(r'#include "([^"]+)"', text):
            walk(inc)
    for s in sources:
        walk(s)
    return sorted(found)


def manifest(base, slug, name, mods, modules, keep_version):
    m = {k: base[k] for k in HEAD if k in base}
    m['slug'], m['name'] = slug, name
    if keep_version:
        m['version'] = keep_version
    m['modules'] = [modules[x] for x in mods]
    return json.dumps(m, indent=2, ensure_ascii=False) + '\n'


def registration(mods, vars_, header='plugin.hpp'):
    lines = ['// ' + GEN, '#include "%s"' % header, '', 'Plugin* pluginInstance;', '']
    lines += ['extern Model* %s;' % vars_[x] for x in mods]
    lines += ['', 'void init(Plugin* p) {', '    pluginInstance = p;']
    lines += ['    p->addModel(%s);' % vars_[x] for x in mods]
    lines += ['}', '']
    return '\n'.join(lines)


def sources_for(mods, lineup):
    out = []
    for x in mods:
        for s in lineup['sources'][x]:
            if s not in out:
                out.append(s)
    return out


def main():
    lineup, modules = load('tools/lineup.json'), load('tools/modules.json')['modules']
    vars_ = model_vars()
    root = load('plugin.json')
    # every module in exactly one plugin, with a source and a Model
    placed = list(lineup['mtx']['modules']) + [m for s in lineup['singles'] for m in s['modules']]
    shared = lineup.get('shared', [])   # modules allowed in more than one plugin (BLANK)
    probs = [m for m in modules if placed.count(m) != 1 and not (m in shared and placed.count(m) >= 1)]
    probs += [m for m in placed if m not in modules or m not in vars_ or m not in lineup['sources']]
    if probs:
        sys.exit('lineup problem with: ' + ', '.join(sorted(set(probs))))

    # MTX pack (repo root)
    mtx = lineup['mtx']
    write('plugin.json', manifest(root, mtx['slug'], mtx['name'], mtx['modules'], modules, root.get('version')))
    write('src/plugin.cpp', registration(mtx['modules'], vars_))
    mk = open(os.path.join(ROOT, 'Makefile'), encoding='utf-8').read()
    block = ('# >>> sources (%s)\nSOURCES += src/plugin.cpp\n' % GEN +
             ''.join('SOURCES += src/%s\n' % s for s in sources_for(mtx['modules'], lineup)) + '# <<< sources')
    if '# >>> sources' in mk:
        mk = re.sub(r'# >>> sources.*?# <<< sources', lambda _: block, mk, flags=re.S)
    else:
        mk = mk.replace('SOURCES += $(wildcard src/*.cpp)', block)
    write('Makefile', mk)

    # singles
    for s in lineup['singles']:
        d = 'singles/' + s['slug']
        old = os.path.join(ROOT, d, 'plugin.json')
        ver = json.load(open(old, encoding='utf-8')).get('version') if os.path.exists(old) else root.get('version')
        write(d + '/plugin.json', manifest(root, s['slug'], s['name'], s['modules'], modules, ver))
        write(d + '/single.cpp', registration(s['modules'], vars_, '../../src/plugin.hpp'))
        srcs = sources_for(s['modules'], lineup)
        write(d + '/Makefile', '\n'.join([
            '# %s (%s)' % (s['name'], ', '.join(modules[m]['name'] for m in s['modules'])),
            '# ' + GEN,
            '# Build from this folder like the MTX pack:  make / make dist / make devinstall   (RACK_DIR = your Rack SDK)',
            'SOURCES += single.cpp ' + ' '.join(srcs),
            'RES := ' + ' '.join(res_files(srcs)),
            'include ../common.mk', '']))
    print('lineup OK: MTX pack %d modules, %d singles (%d modules)' % (
        len(mtx['modules']), len(lineup['singles']), sum(len(s['modules']) for s in lineup['singles'])))


if __name__ == '__main__':
    main()
